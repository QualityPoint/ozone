<template>
  <!-- brand-art: frappe-ui dims every <img> in dark mode; brand art keeps its colours.
       `auto` shows the official inks in light mode and the white-green variant in dark mode. -->
  <span class="inline-block shrink-0" :style="{ width: `${width}px` }">
    <img
      v-if="variant !== 'white'"
      :src="color"
      :alt="t('brand.name')"
      :width="width"
      :height="height"
      :class="['brand-art block h-auto w-full', { 'dark:hidden': variant === 'auto' }]"
      decoding="async"
    />
    <img
      v-if="variant !== 'color'"
      :src="white"
      :alt="t('brand.name')"
      :width="width"
      :height="height"
      :class="['brand-art h-auto w-full', variant === 'auto' ? 'hidden dark:block' : 'block']"
      decoding="async"
    />
  </span>
</template>

<script lang="ts" setup>
import { computed } from "vue"
import { useI18n } from "vue-i18n"

// Generated by scripts/build-brand-assets.py from the official logo.svg.
import color from "@/assets/brand/logo-color.svg"
import white from "@/assets/brand/logo-white.svg"

/** The official logo's viewBox is 500 × 235. */
const ASPECT_RATIO = 500 / 235

const props = withDefaults(
	defineProps<{
		/** `color` on light backgrounds, `white` on the brand green, `auto` follows the theme. */
		variant?: "auto" | "color" | "white"
		/** Rendered height in CSS pixels. */
		height?: number
	}>(),
	{ variant: "auto", height: 48 },
)

const { t } = useI18n()
const width = computed(() => Math.round(props.height * ASPECT_RATIO))
</script>
